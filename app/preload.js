const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("nova", {
  onState: (fn) => ipcRenderer.on("state", (_e, s) => fn(s)),
  onConfig: (fn) => ipcRenderer.on("config", (_e, c) => fn(c)),
  ready: () => ipcRenderer.send("ready"),
  set: (key, value) => ipcRenderer.send("set", { key, value }),
  setMany: (obj) => ipcRenderer.send("setMany", obj),
  identify: () => ipcRenderer.send("identify"),
  onToast: (fn) => ipcRenderer.on("toast", (_e, t) => fn(t)),
  onStats: (fn) => ipcRenderer.on("stats", (_e, s) => fn(s)),
  person: (key, patch) => ipcRenderer.send("person", { key, patch }),
  pickHead: (key) => ipcRenderer.invoke("pickHead", key),
  clearHead: (key) => ipcRenderer.send("clearHead", key),
  pickArt: (kind) => ipcRenderer.invoke("pickArt", kind),
  clearArt: () => ipcRenderer.send("clearArt"),
  profileSave: (name) => ipcRenderer.send("profileSave", name),
  profileDelete: (name) => ipcRenderer.send("profileDelete", name),
  statsReset: () => ipcRenderer.send("statsReset"),
  openHeads: () => ipcRenderer.send("openHeads"),
  win: (what) => ipcRenderer.send("win", what),
  // spotify
  onMusic: (fn) => ipcRenderer.on("music", (_e, s) => fn(s)),
  music: (cmd, arg) => ipcRenderer.send("music", { cmd, arg }),
  playlists: (force) => ipcRenderer.invoke("playlists", !!force),
  hudRect: (r) => ipcRenderer.send("hudRect", r),
  musicVisible: (v) => ipcRenderer.send("musicVisible", !!v),
  musicClickable: (v) => ipcRenderer.send("musicClickable", !!v),
  dbg: (m) => ipcRenderer.send("dbg", String(m)),
  spotifyConnect: (id) => ipcRenderer.invoke("spotifyConnect", id),
  spotifyLogout: () => ipcRenderer.send("spotifyLogout"),
});
